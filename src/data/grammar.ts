/**
 * Грамматика уровня «Минна но Нихонго I», уроки 1-5.
 * Простыми словами: что означает конструкция, как её строить, и примеры.
 * Задания к каждому уроку проверяют именно то, что объяснено в теории.
 */

/** Пример предложения в объяснении */
export interface GrammarExample {
  jp: string
  romaji: string
  ru: string
}

/** Один грамматический пункт урока */
export interface GrammarPoint {
  id: string
  /** Формула конструкции, например "N1 は N2 です" */
  pattern: string
  /** Короткое название пункта */
  title: string
  /** Объяснение простыми словами */
  explanation: string
  examples: GrammarExample[]
}

/** Тип задания: выбор варианта или ввод текста */
export type ExerciseType = 'choice' | 'fill'

/** Одно задание на проверку грамматики */
export interface GrammarExercise {
  id: string
  type: ExerciseType
  /** Вопрос или предложение с пропуском (пропуск обозначен ___) */
  question: string
  /** Варианты ответа — только для типа choice */
  options?: string[]
  /** Правильный ответ */
  answer: string
  /** Подсказка, почему ответ именно такой */
  hint: string
}

/** Урок целиком: теория и задания */
export interface GrammarLesson {
  id: string
  number: number
  title: string
  /** Короткое описание, о чём урок */
  summary: string
  points: GrammarPoint[]
  exercises: GrammarExercise[]
}

